#!/usr/bin/env node

import { execFileSync } from 'child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'fs';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);

const runTsc = (args = []) => {
  const tscPath = require.resolve('typescript/bin/tsc');
  execFileSync(process.execPath, [tscPath, ...args], { stdio: 'inherit' });
};

// The CLI imports its name and version from this module instead of reading
// package.json at runtime, so bundlers (`bun build --compile`, `deno compile`,
// a Node SEA) can see them. Rewritten only when it changes, so src/ mtimes
// stay put across builds.
const writePackageInfo = () => {
  const { name, version } = JSON.parse(readFileSync('package.json', 'utf-8'));
  const contents =
    '// Generated by build.js from package.json. Do not edit.\n' +
    `export const PACKAGE_NAME = ${JSON.stringify(name)};\n` +
    `export const PACKAGE_VERSION = ${JSON.stringify(version)};\n`;
  const file = 'src/generated/package-info.ts';
  if (existsSync(file) && readFileSync(file, 'utf-8') === contents) return;
  mkdirSync('src/generated', { recursive: true });
  writeFileSync(file, contents);
};

console.log('🔨 Building OpenSpec...\n');

// Clean dist directory
if (existsSync('dist')) {
  console.log('Cleaning dist directory...');
  rmSync('dist', { recursive: true, force: true });
}

// Run TypeScript compiler (use local version explicitly)
console.log('Compiling TypeScript...');
try {
  writePackageInfo();
  runTsc(['--version']);
  runTsc();
  console.log('\n✅ Build completed successfully!');
} catch (error) {
  console.error('\n❌ Build failed!');
  process.exit(1);
}
